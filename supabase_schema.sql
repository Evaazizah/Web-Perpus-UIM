-- ====================================================================
-- SKEMA DATABASE PORTAL PERPUSTAKAAN DIGITAL (SUPABASE / POSTGRESQL)
-- ====================================================================

-- 1. TABEL USERS (Profil Pengguna terintegrasi dengan Supabase Auth & KTM)
CREATE TABLE IF NOT EXISTS public.users (
    id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
    nama VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    nim VARCHAR(50),
    prodi VARCHAR(100),
    status_verifikasi VARCHAR(30) DEFAULT 'pending' CHECK (status_verifikasi IN ('pending', 'verified', 'rejected')),
    role VARCHAR(20) DEFAULT 'user' CHECK (role IN ('admin', 'user')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TABEL BOOKS (Katalog Buku)
CREATE TABLE IF NOT EXISTS public.books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    judul VARCHAR(255) NOT NULL,
    penulis VARCHAR(150) NOT NULL,
    kategori VARCHAR(100) NOT NULL,
    sinopsis TEXT,
    cover_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TABEL RATINGS (Pemberian Rating Buku oleh Pengguna)
CREATE TABLE IF NOT EXISTS public.ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user UUID REFERENCES public.users(id) ON DELETE CASCADE NOT NULL,
    id_buku BIGINT REFERENCES public.books(id) ON DELETE CASCADE NOT NULL,
    nilai_rating SMALLINT NOT NULL CHECK (nilai_rating >= 1 AND nilai_rating <= 5),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    -- 1 user hanya bisa memberi rating 1 kali untuk buku yang sama
    CONSTRAINT unique_user_book_rating UNIQUE (id_user, id_buku)
);

-- 4. TABEL BORROWINGS (Peminjaman Buku)
CREATE TABLE IF NOT EXISTS public.borrowings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user UUID REFERENCES public.users(id) ON DELETE CASCADE NOT NULL,
    id_buku BIGINT REFERENCES public.books(id) ON DELETE CASCADE NOT NULL,
    tanggal_pinjam DATE DEFAULT CURRENT_DATE NOT NULL,
    tanggal_kembali DATE,
    status VARCHAR(30) DEFAULT 'dipinjam' CHECK (status IN ('dipinjam', 'dikembalikan', 'terlambat')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ====================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- ====================================================================

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.books ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ratings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.borrowings ENABLE ROW LEVEL SECURITY;

-- Policy Books: Siapapun (termasuk anonim / publik) bisa melihat katalog buku
CREATE POLICY "Public can view books" ON public.books FOR SELECT USING (true);

-- Policy Ratings: Siapapun bisa melihat rating (untuk collaborative filtering)
CREATE POLICY "Public can view ratings" ON public.ratings FOR SELECT USING (true);

-- User yang login bisa menambahkan atau mengedit rating mereka sendiri
CREATE POLICY "Authenticated users can insert ratings" ON public.ratings FOR INSERT WITH CHECK (auth.uid() = id_user);
CREATE POLICY "Authenticated users can update their ratings" ON public.ratings FOR UPDATE USING (auth.uid() = id_user);

-- Policy Users: Siapapun yang terautentikasi bisa membaca data user profil
CREATE POLICY "Public profiles are viewable" ON public.users FOR SELECT USING (true);
CREATE POLICY "Users can update own profile" ON public.users FOR UPDATE USING (auth.uid() = id);

